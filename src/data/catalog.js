/** Минимальная цена среди всех вариантов товара */
export function minPrice(product) {
  if (!product.variants || product.variants.length === 0) return product.price
  const prices = product.variants.map(v => v.price).filter(Boolean)
  if (prices.length === 0) return product.price
  return Math.min(...prices)
}

export function getProductsByCategory(slug) {
  if (!slug) return PRODUCTS
  return PRODUCTS.filter(p => p.category === slug)
}

export function getProductBySlug(slug) {
  return PRODUCTS.find(p => p.slug === slug) || null
}

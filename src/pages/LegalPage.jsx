const SLUGS = Object.keys(LEGAL_DOCS)

export default function LegalPage() {
  const { slug: paramSlug } = useParams()
  const { pathname } = useLocation()
  const slug = paramSlug || pathname.replace(/^\//, '')

  if (!slug || !LEGAL_DOCS[slug]) {
    return <Navigate to="/documents" replace />
  }

  const doc = LEGAL_DOCS[slug]

  return (
    <div className={styles.page}>
      <div className={styles.container}>
        <nav className={styles.breadcrumb}>
          <Link to="/">Главная</Link>
          <span>›</span>
          <Link to="/documents">Документы</Link>
          <span>›</span>
          <span>{doc.title}</span>
        </nav>

        <div className={styles.layout}>
          <aside className={styles.toc}>
            <p className={styles.tocTitle}>Содержание</p>
            <nav>
              {doc.sections.map(s => (
                <a key={s.num} href={`#s${s.num}`} className={styles.tocItem}>
                  {s.num}. {s.title}
                </a>
              ))}
              <a href="#requisites" className={styles.tocItem}>Реквизиты</a>
            </nav>
          </aside>

          <article className={styles.body}>
            <header className={styles.docHeader}>
              <h1 className={styles.title}>{doc.title}</h1>
              {doc.subtitle && <p className={styles.subtitle}>{doc.subtitle}</p>}
              <p className={styles.updated}>{doc.updated}</p>
              {doc.intro && <p className={styles.intro}>{doc.intro}</p>}
            </header>

            {doc.sections.map(s => (
              <section key={s.num} id={`s${s.num}`} className={styles.section}>
                <h2 className={styles.sectionTitle}>{s.num}. {s.title}</h2>
                {s.paragraphs.map((p, i) => (
                  <p key={i} className={styles.para}>{p}</p>
                ))}
              </section>
            ))}

            <section id="requisites" className={styles.section}>
              <h2 className={styles.sectionTitle}>Реквизиты</h2>
              {REQUISITES.split('\n').map((line, i) => (
                <p key={i} className={styles.para}>{line}</p>
              ))}
              {doc.requisitesExtra?.map((line, i) => (
                <p key={i} className={styles.para}>{line}</p>
              ))}
            </section>
          </article>
        </div>
      </div>
    </div>
  )
}
